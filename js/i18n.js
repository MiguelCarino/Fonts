var LOCALE = 'en';

function currentFleetLang() {
    return (window.CarinoLang && window.CarinoLang.current) || 'en';
}

function setLocale(l) {
    LOCALE = (l === 'en' || I18N[l]) ? l : 'en';
}

function t(key) {
    var dict = I18N[LOCALE];
    return (dict && dict[key]) || key;
}

// Static markup: elements carrying data-i18n use their original English text
// as the key (captured on first pass so locale switches stay reversible).
// Elements carrying data-i18n-title hold their English title key in the
// attribute itself.
function applyStaticI18n() {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
        if (!el.dataset.i18nKey) el.dataset.i18nKey = el.textContent.trim();
        el.textContent = t(el.dataset.i18nKey);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
        el.title = t(el.getAttribute('data-i18n-title'));
    });
}

// Helpers for JS-built UI: tag an element so applyStaticI18n() re-translates
// it on every language switch (the key is pinned, so switches are lossless).
function i18nTag(node, key) {
    node.setAttribute('data-i18n', '');
    node.dataset.i18nKey = key;
    node.textContent = t(key);
    return node;
}

function i18nTitle(node, key) {
    node.setAttribute('data-i18n-title', key);
    node.title = t(key);
    return node;
}

// carino-lang.js is deferred and executes before this file, so the fleet
// language is already resolved here — modules building at DOMContentLoaded
// call t() with the right locale from the start.
setLocale(currentFleetLang());

document.addEventListener('DOMContentLoaded', function () {
    setLocale(currentFleetLang());
    applyStaticI18n();
});

window.addEventListener('carino:langchange', function () {
    setLocale(currentFleetLang());
    applyStaticI18n();
    // re-render dynamic surfaces (hints, statuses, counters, kern tables)
    if (window.FontModel && typeof window.FontModel.emit === 'function') {
        window.FontModel.emit();
    }
});
